// Helper to get cities for a county
export function getLocalitatiByJudet(judetCode: string): string[] {
  return LOCALITATI[judetCode] || [];
}

// Helper to get county name by code
export function getJudetName(code: string): string {
  const judet = JUDETE.find((j) => j.code === code);
  return judet?.name || code;
}

